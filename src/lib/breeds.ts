export function plateOf(breed: string): string {
  const known = PLATES[breed];
  if (known != null) {
    return known;
  }

  let hash = 0;
  for (const ch of breed) {
    hash = (hash * 31 + (ch.codePointAt(0) ?? 0)) % 100_000;
  }

  return STRAYS[hash % STRAYS.length] ?? "terrier";
}

export function hasPlate(breed: string): boolean {
  return PLATES[breed] != null;
}

export function plateUrl(breed: string): string {
  return `/breeds/${plateOf(breed)}.webp`;
}
